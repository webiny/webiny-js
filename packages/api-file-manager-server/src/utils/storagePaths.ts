import path from "node:path";

export const getStoragePath = (): string => {
    return String(process.env.WEBINY_LOCAL_STORAGE_PATH);
};

/**
 * The storage key of a file: every file lives under its tenant's folder. The file `key` is always
 * relative to that folder (same as the S3 storage).
 */
export const getFileStorageKey = (tenantId: string, fileKey: string): string => {
    return `tenants/${tenantId}/files/${fileKey.replace(/^\/+/, "")}`;
};

const assertPathSegment = (value: string): void => {
    if (!value || value === "." || value === ".." || /[\\/\0]/.test(value)) {
        throw new Error("Invalid path segment.");
    }
};

/**
 * Security: resolves a storage key (relative to the storage root, e.g.
 * `tenants/<tenant>/files/<id>/<name>`) to an absolute path, and refuses any path that is not
 * inside `<storageRoot>/tenants/<tenantId>/files/`. File keys come from file records, so they must
 * never be trusted to stay inside the tenant's folder on their own.
 */
export const resolveTenantFilePath = (
    storagePath: string,
    tenantId: string,
    storageKey: string
): string => {
    assertPathSegment(tenantId);
    const root = path.resolve(storagePath, "tenants", tenantId, "files");
    const resolved = path.resolve(storagePath, storageKey);
    if (storageKey.includes("\0") || !resolved.startsWith(root + path.sep)) {
        throw new Error("Path is outside of the tenant files folder.");
    }
    return resolved;
};

/**
 * Security: the absolute path of a multipart upload folder. `uploadId` must be an id generated by
 * `CreateMultiPartUpload` (`mdbid`), so it can never point at another folder.
 */
export const resolveMultipartUploadDir = (
    storagePath: string,
    tenantId: string,
    uploadId: string
): string => {
    assertPathSegment(tenantId);
    if (!isValidUploadId(uploadId)) {
        throw new Error("Invalid upload id.");
    }
    return path.resolve(storagePath, "tenants", tenantId, "multipart", uploadId);
};

export const isValidUploadId = (uploadId: unknown): uploadId is string => {
    return typeof uploadId === "string" && /^[a-f0-9]{24}$/.test(uploadId);
};
